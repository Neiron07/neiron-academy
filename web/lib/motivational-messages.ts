function dayOfYear(d: Date): number {
  const start = new Date(d.getFullYear(), 0, 0);
  const diff = d.getTime() - start.getTime();
  return Math.floor(diff / 86_400_000);
}

/** studentId сдвигает стартовую точку по кругу — соседи по рейтингу не видят одно и то же слово в слово каждый день. */
function idOffset(studentId?: string): number {
  if (!studentId) return 0;
  let hash = 0;
  for (let i = 0; i < studentId.length; i++) hash = (hash * 31 + studentId.charCodeAt(i)) >>> 0;
  return hash;
}

export function getDailyMessage(gender: StudentGender | null, studentId?: string, date: Date = new Date()): string {
  const list = gender === 'male' ? MALE_MESSAGES : gender === 'female' ? FEMALE_MESSAGES : NEUTRAL_MESSAGES;
  const index = (dayOfYear(date) + idOffset(studentId)) % list.length;
  return list[index]!;
}
