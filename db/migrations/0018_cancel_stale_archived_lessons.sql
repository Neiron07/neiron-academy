-- =====================================================================
-- Разовая уборка: архивация группы раньше не закрывала её ещё не
-- проведённые (planned) уроки — они бесконечно висели в «Незакрытые
-- уроки» у преподавателя и в дашборде. Сама причина исправлена в коде
-- (admin.ts, PATCH/DELETE /groups/:id теперь закрывают такие уроки),
-- эта миграция разово подчищает то, что уже накопилось в проде.
-- =====================================================================

update lessons l
   set status = 'cancelled',
       cancel_reason = 'Группа архивирована',
       cancelled_by_school = true
  from groups g
 where g.id = l.group_id
   and g.status = 'archived'
   and l.status = 'planned';
